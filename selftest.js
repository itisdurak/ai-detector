// Быстрая проверка калибровки: node selftest.js
const d = require('./detector.js');

const cases = {
  'ИИ-пример': d.EXAMPLES.ai,
  'Человек-пример': d.EXAMPLES.human,
  'Формальный человек': `Согласно пункту 3.2 договора, исполнитель обязуется передать заказчику результаты работ в срок до 30 календарных дней с момента подписания акта. Однако стороны вправе продлить этот срок по mutual соглашению. В случае нарушения сроков, предусмотренных настоящим разделом, заказчик вправе требовать уплаты неустойки в размере 0,1% за каждый день просрочки. Все споры разрешаются в порядке, установленном законодательством.`,
  'Короткий': 'Сегодня хорошая погода. Я пошёл гулять в парк.',
  'Смешанный': `Меня зовут Артём, я пишу бэкенд на Python. Важно отметить, что в современном мире микросервисы играют важную роль. Но если честно, монолит иногда проще. Вчера полдня дебажил миграцию, чуть не сломал прод.`,
};

for (const [name, text] of Object.entries(cases)) {
  const r = d.analyze(text);
  if (!r.ok) { console.log(name, '->', r.error); continue; }
  console.log(
    name.padEnd(22),
    String(r.percent).padStart(3) + '%',
    'conf', String(r.confidence).padStart(3) + '%',
    '|', r.verdict.label
  );
  console.log(
    '   ' + r.signals.map(s => s.id.slice(0, 6) + ':' + s.score.toFixed(2)).join(' ')
  );
  console.log('   маркеры:', r.foundPhrases.map(f => f.phrase + '×' + f.count).join(', ') || '—');
}
